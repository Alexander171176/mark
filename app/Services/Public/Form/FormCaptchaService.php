<?php

namespace App\Services\Public\Form;

use Illuminate\Support\Facades\Cache;
use Illuminate\Support\Str;

class FormCaptchaService
{
    /**
     * Отдельный Redis Cache Store для CAPTCHA.
     */
    private const CACHE_STORE = 'form_protection';

    /**
     * Хранилище токенов, ответов и блокировок CAPTCHA.
     */
    private function cache(): \Illuminate\Contracts\Cache\Repository
    {
        return Cache::store(self::CACHE_STORE);
    }

    /*
    |--------------------------------------------------------------------------
    | CAPTCHA Configuration
    |--------------------------------------------------------------------------
    */

    private const LENGTH = 5;

    private const TTL_SECONDS = 300;

    private const MAX_ATTEMPTS = 5;

    private const LOCK_SECONDS = 10;

    private const LOCK_WAIT_SECONDS = 3;

    private const CHARACTERS =
        'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';

    /*
    |--------------------------------------------------------------------------
    | Generate
    |--------------------------------------------------------------------------
    */

    /**
     * Создать CAPTCHA для конкретной публичной формы.
     *
     * Правильный ответ хранится только на сервере.
     * Клиент получает токен, изображение и срок действия.
     */
    public function generate(int $formId): array
    {
        /*
        |--------------------------------------------------------------------------
        | Случайный код
        |--------------------------------------------------------------------------
        */

        $code = '';

        $characters = self::CHARACTERS;

        $max = strlen($characters) - 1;

        for ($i = 0; $i < self::LENGTH; $i++) {
            $code .= $characters[
            random_int(0, $max)
            ];
        }

        /*
        |--------------------------------------------------------------------------
        | Уникальный токен
        |--------------------------------------------------------------------------
        */

        $token = Str::random(64);

        /*
        |--------------------------------------------------------------------------
        | Фиксированное время окончания
        |--------------------------------------------------------------------------
        */

        $expiresAt = now()->addSeconds(
            self::TTL_SECONDS
        );

        /*
        |--------------------------------------------------------------------------
        | Сохранение задания
        |--------------------------------------------------------------------------
        */

        $this->cache()->put(
            $this->cacheKey($token),
            [
                'form_id' => $formId,

                'answer_hash' => hash(
                    'sha256',
                    $code
                ),

                'attempts' => 0,

                'expires_at' => $expiresAt->timestamp,
            ],
            $expiresAt
        );

        /*
        |--------------------------------------------------------------------------
        | Публичный ответ
        |--------------------------------------------------------------------------
        */

        return [
            'token' => $token,

            'image' => $this->generateSvg($code),

            'expires_in' => self::TTL_SECONDS,
        ];
    }

    /*
    |--------------------------------------------------------------------------
    | Verify
    |--------------------------------------------------------------------------
    */

    /**
     * Проверить CAPTCHA.
     *
     * Проверка выполняется внутри атомарной блокировки.
     *
     * Успешно использованный токен удаляется.
     * Неправильный ответ увеличивает счётчик попыток.
     * Первоначальный срок действия не продлевается.
     */
    public function verify(
        int $formId,
        string $token,
        string $answer
    ): bool {
        /*
        |--------------------------------------------------------------------------
        | Проверка формата токена
        |--------------------------------------------------------------------------
        */

        if (
            !preg_match(
                '/^[A-Za-z0-9]{64}$/',
                $token
            )
        ) {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Ключи Cache
        |--------------------------------------------------------------------------
        */

        $key = $this->cacheKey($token);

        $lockKey = $this->lockKey($token);

        /*
        |--------------------------------------------------------------------------
        | Атомарная блокировка
        |--------------------------------------------------------------------------
        */

        return $this->cache()->lock(
            $lockKey,
            self::LOCK_SECONDS
        )->block(
            self::LOCK_WAIT_SECONDS,
            function () use (
                $formId,
                $answer,
                $key
            ): bool {
                /*
                |--------------------------------------------------------------------------
                | Получение задания
                |--------------------------------------------------------------------------
                */

                $data = $this->cache()->get($key);

                if (!is_array($data)) {
                    return false;
                }

                /*
                |--------------------------------------------------------------------------
                | Проверка принадлежности форме
                |--------------------------------------------------------------------------
                */

                if (
                    (int) ($data['form_id'] ?? 0)
                    !== $formId
                ) {
                    return false;
                }

                /*
                |--------------------------------------------------------------------------
                | Проверка срока действия
                |--------------------------------------------------------------------------
                */

                $expiresAt = (int) (
                    $data['expires_at'] ?? 0
                );

                if (
                    $expiresAt <= 0
                    || now()->timestamp >= $expiresAt
                ) {
                    $this->cache()->forget($key);

                    return false;
                }

                /*
                |--------------------------------------------------------------------------
                | Проверка количества попыток
                |--------------------------------------------------------------------------
                */

                $attempts = (int) (
                    $data['attempts'] ?? 0
                );

                if (
                    $attempts >= self::MAX_ATTEMPTS
                ) {
                    $this->cache()->forget($key);

                    return false;
                }

                /*
                |--------------------------------------------------------------------------
                | Нормализация ответа
                |--------------------------------------------------------------------------
                */

                $normalizedAnswer = strtoupper(
                    trim($answer)
                );

                /*
                |--------------------------------------------------------------------------
                | Сравнение хешей
                |--------------------------------------------------------------------------
                */

                $valid = hash_equals(
                    (string) (
                        $data['answer_hash'] ?? ''
                    ),
                    hash(
                        'sha256',
                        $normalizedAnswer
                    )
                );

                /*
                |--------------------------------------------------------------------------
                | Успешная проверка
                |--------------------------------------------------------------------------
                */

                if ($valid) {
                    $this->cache()->forget($key);

                    return true;
                }

                /*
                |--------------------------------------------------------------------------
                | Неправильный ответ
                |--------------------------------------------------------------------------
                */

                $attempts++;

                if (
                    $attempts >= self::MAX_ATTEMPTS
                ) {
                    $this->cache()->forget($key);

                    return false;
                }

                /*
                |--------------------------------------------------------------------------
                | Обновление счётчика
                |--------------------------------------------------------------------------
                |
                | Используем исходный expires_at.
                | Срок действия CAPTCHA не продлевается.
                |
                */

                $data['attempts'] = $attempts;

                $this->cache()->put(
                    $key,
                    $data,
                    $expiresAt
                );

                return false;
            }
        );
    }

    /*
    |--------------------------------------------------------------------------
    | Cache Keys
    |--------------------------------------------------------------------------
    */

    /**
     * Ключ задания CAPTCHA.
     */
    private function cacheKey(string $token): string
    {
        return 'form_captcha:' . hash(
                'sha256',
                $token
            );
    }

    /**
     * Ключ атомарной блокировки.
     */
    private function lockKey(string $token): string
    {
        return 'form_captcha_lock:' . hash(
                'sha256',
                $token
            );
    }

    /*
    |--------------------------------------------------------------------------
    | SVG Generator
    |--------------------------------------------------------------------------
    */

    /**
     * Создать SVG-изображение CAPTCHA.
     *
     * Используется только сгенерированный
     * сервером набор символов.
     */
    private function generateSvg(
        string $code
    ): string {
        $width = 220;

        $height = 70;

        /*
        |--------------------------------------------------------------------------
        | Фоновые линии
        |--------------------------------------------------------------------------
        */

        $lines = '';

        for ($i = 0; $i < 12; $i++) {
            $x1 = random_int(0, $width);

            $y1 = random_int(0, $height);

            $x2 = random_int(0, $width);

            $y2 = random_int(0, $height);

            $lines .= sprintf(
                '<line
                    x1="%d"
                    y1="%d"
                    x2="%d"
                    y2="%d"
                    stroke="#94a3b8"
                    stroke-opacity="0.35"
                    stroke-width="1"
                />',
                $x1,
                $y1,
                $x2,
                $y2
            );
        }

        /*
        |--------------------------------------------------------------------------
        | Символы
        |--------------------------------------------------------------------------
        */

        $letters = '';

        foreach (
            str_split($code) as $index => $letter
        ) {
            $x = 25 + ($index * 38);

            $y = random_int(43, 53);

            $rotation = random_int(-15, 15);

            $letters .= sprintf(
                '<text
                    x="%d"
                    y="%d"
                    transform="rotate(%d %d %d)"
                    font-family="monospace"
                    font-size="36"
                    font-weight="bold"
                    fill="#1e293b"
                >%s</text>',
                $x,
                $y,
                $rotation,
                $x,
                $y,
                $letter
            );
        }

        /*
        |--------------------------------------------------------------------------
        | Готовый SVG
        |--------------------------------------------------------------------------
        */

        return sprintf(
            '<svg
                xmlns="http://www.w3.org/2000/svg"
                width="%d"
                height="%d"
                viewBox="0 0 %d %d"
                role="img"
            >
                <rect
                    width="100%%"
                    height="100%%"
                    rx="8"
                    fill="#f1f5f9"
                />
                %s
                %s
            </svg>',
            $width,
            $height,
            $width,
            $height,
            $lines,
            $letters
        );
    }
}
